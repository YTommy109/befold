/// ビューアウィンドウの種別(TASK-593.2)。
///
/// **`Bool` のフラグにしない。** 「サイドバーを開かせない」だけなら真偽値で足りるが、
/// ツールバーの有無・タブ合流の可否・セッション復元の対象かどうかも同じ判定で決まる。
/// 1 つの `Bool` にそれらを兼ねさせると、後から「ツールバーだけ出したい種別」が
/// 現れたときに意味が割れる。列挙にしておけば同じコストで名前が付く
/// (spec の「案の比較」で案 C を退けた理由)。
///
/// 種別は**生成時に決まり、窓の生涯を通じて変わらない**。切り替えを許すと
/// 「ツールバーを後から生やす」「畳んだサイドバーを開かせる」経路が必要になり、
/// この型が消しているはずの状態が戻ってくる。
enum ViewerWindowKind: Equatable {
    /// 通常のビューア窓。サイドバー・ツールバーを持ち、タブへ合流し、セッション復元の対象。
    case viewer
    /// プレゼン用のスライド窓。サイドバー無し・ツールバー無し・タブ合流なし・復元対象外。
    case slide

    /// サイドバーを開けるか。`false` の種別では `toggleSidebar(_:)` が no-op になり、
    /// ⌘S も無効になる。
    ///
    /// **述語をここに置く。** 呼び出し側で `kind == .slide` と書くと、種別が 3 つ目に
    /// 増えたとき「slide 以外は開ける」という前提が黙って残る。
    var allowsSidebar: Bool {
        self == .viewer
    }

    /// ツールバーを持つか。
    var hasToolbar: Bool {
        self == .viewer
    }

    /// 既存の窓のタブグループへ合流してよいか。
    var joinsTabs: Bool {
        self == .viewer
    }

    /// セッション復元の対象か。`false` の種別は終了時のスナップショットに入らない。
    var isRestorable: Bool {
        self == .viewer
    }
}
